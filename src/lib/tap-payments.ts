const TAP_API_BASE = "https://api.tap.company/v2";

function tapHeaders(): HeadersInit {
  const key = config.tap.secretKey;
  if (!key) throw new Error("TAP_SECRET_KEY is not configured.");
  // Warn if it looks like a publishable key
  if (!key.startsWith("sk_")) {
    console.warn("[tap] TAP_SECRET_KEY looks like a publishable key (should start with sk_)");
  }
  return {
    Authorization: `Bearer ${key}`,
    "Content-Type": "application/json",
    Accept: "application/json",
  };
}

/**
 * Creates a Tap charge and returns the charge object including the hosted
 * payment page URL. The caller should 303-redirect the user to
 * `charge.transaction.url`.
 *
 * If transaction.url is missing from the response, returns { ok: false }.
 */
export async function createTapCharge(
  input: TapChargeInput,
): Promise<{ ok: true; charge: TapChargeResponse } | { ok: false; error: string }> {
  const {
    amount,
    description,
    statementDescriptor = "SmarThinkerz",
    customer,
    metadata,
    redirectUrl,
    postUrl,
    transactionRef,
    orderRef,
  } = input;

  const body: Record<string, unknown> = {
    amount,
    currency: "USD",
    threeDSecure: true,
    save_card: false,
    description,
    statement_descriptor: statementDescriptor,
    metadata,
    reference: {
      transaction: transactionRef ?? generateTransactionRef(metadata.plan, metadata.cycle),
      order: orderRef ?? generateOrderRef(),
    },
    receipt: { email: true, sms: false },
    customer: {
      first_name: customer.first_name,
      last_name: customer.last_name,
      email: customer.email,
      ...(customer.phone
        ? { phone: { country_code: customer.phone.country_code, number: customer.phone.number } }
        : {}),
    },
    source: { id: "src_all" },
    redirect: { url: redirectUrl },
    ...(postUrl ? { post: { url: postUrl } } : {}),
  };

  try {
    const res = await fetch(`${TAP_API_BASE}/charges`, {
      method: "POST",
      headers: tapHeaders(),
      body: JSON.stringify(body),
    });

    const data = await res.json();

    if (!res.ok) {
      const tapErr = data as TapError;
      const msg =
        tapErr.errors?.[0]?.description ??
        `Tap API error ${res.status}: ${JSON.stringify(data)}`;
      console.error("[tap] createTapCharge error:", msg);
      return { ok: false, error: msg };
    }

    const charge = data as TapChargeResponse;

    // Spec: if transaction.url is missing, return 502 — we surface as error
    if (!charge.transaction?.url) {
      console.error("[tap] createTapCharge: missing transaction.url in response", data);
      return { ok: false, error: "Tap did not return a payment URL. Please try again." };
    }

    return { ok: true, charge };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error("[tap] createTapCharge network error:", msg);
    return { ok: false, error: msg };
  }
}

/**
 * Retrieves a charge by ID from Tap.
 * Used by the /checkout/return handler to re-fetch the authoritative status.
 * NEVER trust the tap_id query param directly — always re-fetch.
 */
export async function retrieveCharge(
  chargeId: string,
): Promise<{ ok: true; charge: TapChargeResponse } | { ok: false; error: string }> {
  try {
    const res = await fetch(`${TAP_API_BASE}/charges/${chargeId}`, {
      method: "GET",
      headers: tapHeaders(),
    });

    const data = await res.json();

    if (!res.ok) {
      const tapErr = data as TapError;
      const msg = tapErr.errors?.[0]?.description ?? `Tap API error ${res.status}`;
      return { ok: false, error: msg };
    }

    return { ok: true, charge: data as TapChargeResponse };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return { ok: false, error: msg };
  }
}

/**
 * Issues a refund for a charge.
 * POST /v2/refunds
 */
export async function refundCharge(
  chargeId: string,
  amount: number,
  reason = "requested_by_customer",
): Promise<{ ok: true; refundId: string } | { ok: false; error: string }> {
  try {
    const res = await fetch(`${TAP_API_BASE}/refunds`, {
      method: "POST",
      headers: tapHeaders(),
      body: JSON.stringify({ charge_id: chargeId, amount, currency: "USD", reason }),
    });

    const data = await res.json();

    if (!res.ok) {
      const tapErr = data as TapError;
      const msg = tapErr.errors?.[0]?.description ?? `Tap refund error ${res.status}`;
      return { ok: false, error: msg };
    }

    return { ok: true, refundId: (data as { id: string }).id };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return { ok: false, error: msg };
  }
}

