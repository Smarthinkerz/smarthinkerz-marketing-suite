/**
 * Tap Payments API helpers — server-side only.
 *
 * Tap API reference: https://developers.tap.company/reference
 *
 * Currency: USD (major units, e.g. 49 = USD 49.00).
 * Model: server-initiated hosted checkout (redirect-based).
 *
 * Flow:
 *   1. Server calls createCharge() → gets charge.transaction.url
 *   2. Server redirects customer to transaction.url (Tap hosted page)
 *   3. Tap redirects customer back to /checkout/return?tap_id=<charge_id>
 *   4. Return handler calls retrieveCharge() to re-fetch status (never trust query params)
 *   5. Tap also POSTs to /api/tap/webhook for out-of-band reconciliation
 *
 * NEVER import this file in Client Components.
 */
import { config } from "@/lib/config";

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface TapCustomer {
  first_name: string;
  last_name: string;
  email: string;
  phone?: {
    country_code: string; // e.g. "971" (no +)
    number: string;       // e.g. "501234567"
  };
}

export interface TapChargeInput {
  /** Amount in USD major units (e.g. 49 = USD 49.00) */
  amount: number;
  /** Human-readable plan description */
  description: string;
  /** Short descriptor on bank statement — max 22 chars */
  statementDescriptor?: string;
  customer: TapCustomer;
  /**
   * Metadata stored on the charge for reconciliation.
   * plan, cycle, product, display, plan_name per spec.
   */
  metadata: {
    plan: string;
    cycle: string;
    product: string;
    display: string;
    plan_name: string;
    [key: string]: string;
  };
  /** Where Tap redirects the customer after payment (carries ?tap_id=charge_id) */
  redirectUrl: string;
  /** Server-to-server per-charge callback URL */
  postUrl?: string;
  /** Unique transaction reference (generated by caller) */
  transactionRef?: string;
  /** Unique order reference (generated by caller) */
  orderRef?: string;
}

export interface TapChargeResponse {
  id: string;
  status: string; // INITIATED | CAPTURED | AUTHORIZED | IN_PROGRESS | PENDING | CANCELLED | FAILED | DECLINED | ABANDONED | REFUNDED
  amount: number;
  currency: string;
  description?: string;
  metadata?: Record<string, string>;
  reference?: {
    transaction?: string;
    order?: string;
    gateway?: string;
    payment?: string;
  };
  transaction: {
    url: string;     // Tap hosted payment page — redirect user here
    created?: string;
    asof?: string;
  };
  response?: {
    code?: string;
    message?: string;
  };
  customer?: {
    first_name?: string;
    last_name?: string;
    email?: string;
  };
}

export interface TapError {
  errors?: Array<{ code?: string; description?: string }>;
}

/**
 * Maps a raw Tap charge status to the internal order status.
 *
 * Tap status       → Internal status
 * CAPTURED/AUTHORIZED → paid
 * INITIATED/IN_PROGRESS/PENDING → initiated
 * CANCELLED        → cancelled
 * anything else    → failed
 */
export type OrderStatus = "initiated" | "paid" | "failed" | "cancelled" | "refunded" | "partially_refunded" | "refunding";

export function mapTapStatus(tapStatus: string): OrderStatus {
  const s = tapStatus?.toUpperCase();
  if (s === "CAPTURED" || s === "AUTHORIZED") return "paid";
  if (s === "INITIATED" || s === "IN_PROGRESS" || s === "PENDING") return "initiated";
  if (s === "CANCELLED") return "cancelled";
  if (s === "REFUNDED") return "refunded";
  return "failed";
}

// ---------------------------------------------------------------------------
// Phone number parser
// ---------------------------------------------------------------------------

/**
 * Parses a raw phone string into Tap's required { country_code, number } format.
 * Tap expects country_code WITHOUT the leading + (e.g. "971" not "+971").
 *
 * Examples:
 *  "+971 501234567"  → { country_code: "971", number: "501234567" }
 *  "+96896737452"    → { country_code: "968", number: "96737452" }
 *  "00971501234567"  → { country_code: "971", number: "501234567" }
 *  "501234567"       → { country_code: "971", number: "501234567" } (defaults to UAE)
 *  "1 5551234567"    → { country_code: "1",   number: "5551234567" }
 */
export function parseTapPhone(raw: string): { country_code: string; number: string } {
  const cleaned = raw.trim().replace(/\s+/g, "");
  const normalized = cleaned.startsWith("00") ? "+" + cleaned.slice(2) : cleaned;

  if (!normalized.startsWith("+")) {
    return { country_code: "971", number: normalized };
  }

  const digits = normalized.slice(1);
  const knownCodes: Record<string, number> = {
    "966": 3, "971": 3, "968": 3, "974": 3, "973": 3, "965": 3, "967": 3, "962": 3,
    "963": 3, "964": 3, "961": 3, "970": 3, "972": 3, "212": 3, "213": 3,
    "216": 3, "218": 3, "249": 3, "252": 3,
    "20": 2, "44": 2, "49": 2, "33": 2, "39": 2, "34": 2,
    "1": 1,
  };

  for (const len of [3, 2, 1]) {
    const candidate = digits.slice(0, len);
    if (knownCodes[candidate] !== undefined) {
      return { country_code: candidate, number: digits.slice(len) };
    }
  }

  return { country_code: digits.slice(0, 3), number: digits.slice(3) };
}

