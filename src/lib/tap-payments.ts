/** Generates a unique transaction reference: txn_<slug>_<cycle>_<ts> */
export function generateTransactionRef(plan: string, cycle: string): string {
  const slug = plan.replace(/[^a-z0-9]/gi, "-").toLowerCase();
  const cyc = cycle.replace(/[^a-z0-9]/gi, "-").toLowerCase();
  return `txn_${slug}_${cyc}_${Date.now()}`;
}

/** Generates a unique order reference: ord_<ts>_<rand> */
export function generateOrderRef(): string {
  const rand = Math.random().toString(36).slice(2, 8);
  return `ord_${Date.now()}_${rand}`;
}

